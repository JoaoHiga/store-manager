package com.storemanager.catalog.usecase;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.storemanager.catalog.domain.Category;
import com.storemanager.catalog.domain.Product;
import java.math.BigDecimal;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class CreateProductUseCaseTest {

    private final InMemoryCategoryRepository categoryRepository = new InMemoryCategoryRepository();
    private final InMemoryProductRepository productRepository = new InMemoryProductRepository();
    private final CreateProductUseCase useCase = new CreateProductUseCase(productRepository, categoryRepository);

    private Category category;

    @BeforeEach
    void seedCategory() {
        category = new CreateCategoryUseCase(categoryRepository).execute("Celulares", null);
    }

    @Test
    void createsAProductWithAnAutoGeneratedSku() {
        Product product =
                useCase.execute("iPhone 12", null, category.getId(), null, null, new BigDecimal("350"), 3);

        assertThat(product.getId()).isNotNull();
        assertThat(product.getSku()).startsWith("PRD-");
        assertThat(product.isActive()).isTrue();
    }

    @Test
    void rejectsANonexistentCategory() {
        assertThatThrownBy(
                        () -> useCase.execute("iPhone 12", null, 999L, null, null, new BigDecimal("350"), 3))
                .isInstanceOf(CategoryNotFoundException.class);
    }

    @Test
    void rejectsANegativeStockQuantity() {
        assertThatThrownBy(
                        () ->
                                useCase.execute(
                                        "iPhone 12", null, category.getId(), null, null, new BigDecimal("350"), -1))
                .isInstanceOf(IllegalArgumentException.class);
    }
}
